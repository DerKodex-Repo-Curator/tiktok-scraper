def test_cookie_status_critical_cookie_name(tmp_path):
    """Critical cookies: msToken, ttwid, tt_chain_token, sessionid."""
    f = tmp_path / "cookies.txt"
    _write_cookies(f, [
        (".tiktok.com", str(int(time.time()) - 100), "sessionid", "abc"),
    ])
    status = get_cookie_status(str(f))
    assert status["status"] == "expired"
    assert "sessionid" in status["expired"]


def test_cookie_valid_days_calculation(tmp_path):
    """valid_days is calculated from the soonest-expiring cookie."""
    f = tmp_path / "cookies.txt"
    _write_cookies(f, [
        (".tiktok.com", str(int(time.time()) + 100 * 86400), "ttwid", "def"),
        (".tiktok.com", str(int(time.time()) + 10 * 86400), "msToken", "abc"),
    ])
    status = get_cookie_status(str(f))
    assert status["valid_days"] is not None
    assert 9 <= status["valid_days"] <= 10
    assert status["critical_cookie"] == "msToken"