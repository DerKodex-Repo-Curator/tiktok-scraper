def test_cookie_status_only_session_cookies(tmp_path):
    """Only session cookies (expiry=0) — status ok, valid_days=None."""
    f = tmp_path / "cookies.txt"
    _write_cookies(f, [
        (".tiktok.com", "0", "session_id", "xyz"),
        (".tiktok.com", "0", "theme", "dark"),
    ])
    status = get_cookie_status(str(f))
    assert status["status"] == "ok"
